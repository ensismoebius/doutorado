// No copying, no dynamic allocation
// Only wavelets with instantiated get_wavelet<Wavelet>() will be compiled
template <typename Wavelet>
constexpr auto get_wavelet() -> std::span<const double>
{
    return WaveletTraits<Wavelet>::coeffs;
}

